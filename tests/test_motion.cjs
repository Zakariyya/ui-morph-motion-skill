const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const source = path.join(__dirname, '../assets/motion.js');
assert.ok(fs.existsSync(source), 'analytic motion helpers are missing');
const M = require(source);
const example = fs.readFileSync(path.join(__dirname,'../assets/example.html'),'utf8');
const embedded = example.split('/* BEGIN MOTION HELPERS */\n')[1].split('/* END MOTION HELPERS */')[0];
assert.equal(embedded, fs.readFileSync(source,'utf8'), 'example must inline the current helpers exactly');
const near = (x, y, eps = 1e-5) => assert.ok(Math.abs(x-y) < eps, `${x} != ${y}`);
near(M.release(0, 160, 220, 100), 160);
near((M.release(1e-7, 160, 220, 100)-160)/1e-7, 220, 0.01);
near(M.release(3, 160, 220, 100), 100, 1e-4);
const events = [{t:0.2, value:300}, {t:0.4, value:100}, {t:0.6, value:200}];
const ordered = [0, 0.3, 0.5, 0.7, 1].map(t => M.track(t, 80, events));
[4, 2, 0, 3, 1].forEach(i => near(M.track([0, 0.3, 0.5, 0.7, 1][i], 80, events), ordered[i]));
const e = 1e-7;
near(M.track(0.4-e, 80, events), M.track(0.4+e, 80, events), 0.002);
const drag = {start:1, end:2, from:20, to:160, target:100};
near(M.drag(1.5, drag), 90);
near(M.drag(2, drag), 160);
near((M.drag(2+e, drag)-M.drag(2, drag))/e, 140, 0.01);
console.log('motion: release position/velocity, target superposition, random seek and drag continuity passed');
